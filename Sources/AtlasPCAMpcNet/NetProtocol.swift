/// The DISTRIBUTED malicious-with-abort (SPDZ-style) composition protocol: same circuit and semantics as the in-process runner (allow = AND, t = MAX,
/// r = MAX via thermometers, authenticated Beaver multiplication, batched MAC-check before any output), but each party is its own node holding only its
/// own shares and every opening is a message over the TLS `Mesh`. Rounds: prep, coin1-*, sac-rho, sac-tau, inputs (or in-check), mul0.., out, the
/// pairwise tag rounds, coin-c/o, sig-c/o, digest, and on a failed MAC-check a blame round. No output is decoded until the MAC-check and the transcript
/// echo pass. Offline modes: `trusted-dealer` (a separate node that knows every share and key) and `no-dealer` (the parties derive everything from OT).
/// There is no security proof; the echo is a hash exchange, not Byzantine agreement; the dealer is trusted for privacy.
public enum NetProtocol {
    public static let T_M = 3
    static let DEFAULT_Q = 100
    static let PREP_CHUNK = 30_000
    static let MASK61: UInt64 = (1 << 61) - 1

    public static func chainCount(_ Q: Int) -> Int { 1 + T_M + Q }

    /// (total numbers, triples, inputs) of one party's dealer slice.
    static func prepLayout(_ n: Int, _ C: Int, _ keys: Int, _ partners: Int, _ tagged: Bool) -> (nums: Int, triples: Int, inputs: Int) {
        let aw = NetPa.awWidth(n, keys, tagged)
        let triples = (n - 1) * C
        let inputs = n * C
        return ((tagged ? 1 : 0) + keys * NetPa.paWidth(n, tagged) + triples * PCAMpc.NetCodec.sharingsPerTriple(partners) * aw + inputs * aw + C, triples, inputs)
    }

    // MARK: dealer

    private static func dealPA(_ x: [UInt64], _ deltas: [UInt64], _ rng: inout Field.Rng) -> [PA] {
        let n = x.count
        var K = [[UInt64]](repeating: [UInt64](repeating: 0, count: n), count: n)
        for i in 0..<n { for j in 0..<n { K[i][j] = i == j ? 0 : rng.next() } }
        var out: [PA] = []
        for p in 0..<n {
            var tag: [UInt64] = []
            var key: [UInt64] = []
            for j in 0..<n {
                tag.append(j == p ? 0 : Field.add(K[p][j], Field.mul(deltas[j], x[p])))
                key.append(j == p ? 0 : K[j][p])
            }
            out.append(PA(x: x[p], tag: tag, key: key))
        }
        return out
    }

    private static func dealAW(_ sv: Spdz.AuthSV, _ deltas: [UInt64], _ rng: inout Field.Rng) -> [AW] {
        let n = sv.value.count
        let comps = [sv.value, sv.mac] + sv.extraMac
        let dealt = comps.map { dealPA($0, deltas, &rng) }
        return (0..<n).map { p in AW(v: dealt[0][p], m: Array(dealt.dropFirst().map { $0[p] })) }
    }

    /// The TRUSTED DEALER role: samples the MAC keys, verification keys, sacrifice-certified authenticated triples and input masks, and ships each party
    /// only its own slice. It never sees an input bit, but it knows every key and share.
    public static func runDealer(_ cfg: DealerConfig) throws {
        let n = cfg.n
        let mesh = cfg.mesh
        guard cfg.insecureTrustedDealer else {
            throw NetError("runDealer requires insecureTrustedDealer (a dealer sees every share and MAC key; the default offline phase has no dealer)")
        }
        let Q = cfg.Q ?? DEFAULT_Q
        var rng = Field.Rng.make(seed: cfg.seed)
        let C = chainCount(Q)
        let ctx = try Spdz.setupMac(n, &rng, keys: Spdz.MAC_KEYS)
        let keys = ctx.macKeys
        var deltas: [UInt64] = []
        for _ in 0..<n {
            var d = rng.next()
            while d == 0 { d = rng.next() }
            deltas.append(d)
        }
        var perParty: [[UInt64]] = (0..<n).map { [deltas[$0]] }
        let alphaPA = keys.map { dealPA($0.alphaShares, deltas, &rng) }
        for p in 0..<n { for a in alphaPA { perParty[p] += try NetPa.paFlat(a[p], p, n, true) } }

        let nTriples = (n - 1) * C
        for _ in 0..<nTriples {
            let tr = try Spdz.genTripleWithPartners(ctx, &rng, partners: Spdz.SACRIFICE_PARTNERS, fault: cfg.fault)
            var sharings = [tr.keep.a, tr.keep.b, tr.keep.c]
            for q in tr.partners { sharings.append(q.a); sharings.append(q.c) }
            for sv in sharings {
                let aws = dealAW(sv, deltas, &rng)
                for p in 0..<n { perParty[p] += try NetPa.awFlat(aws[p], p, n, true) }
            }
        }
        var masksByOwner = [[UInt64]](repeating: [], count: n)
        for q in 0..<(n * C) {
            let owner = q / C
            let r = rng.next()
            masksByOwner[owner].append(r)
            var sv = try Spdz.authShare(r, ctx, &rng)
            if let f = cfg.macFaultAtInput, f == q { sv.mac[0] = Field.add(sv.mac[0], 1) }
            let aws = dealAW(sv, deltas, &rng)
            for p in 0..<n { perParty[p] += try NetPa.awFlat(aws[p], p, n, true) }
        }
        for p in 0..<n { perParty[p] += masksByOwner[p] }

        for p in 0..<n {
            let nums = perParty[p].map { NetUtil.hx($0) }
            let chunks = max(1, (nums.count + PREP_CHUNK - 1) / PREP_CHUNK)
            func slice(_ a: Int, _ b: Int) -> JSONValue { .array(nums[a..<b].map { .string($0) }) }
            try mesh.send(p, "prep", .object(["total": .int(Int64(nums.count)), "chunks": .int(Int64(chunks)), "nums": slice(0, min(PREP_CHUNK, nums.count))]))
            for c in 1..<max(chunks, 1) where chunks > 1 {
                try mesh.send(p, "prep.\(c)", slice(c * PREP_CHUNK, min((c + 1) * PREP_CHUNK, nums.count)))
            }
        }
        mesh.finish()
    }

    // MARK: party

    /// Uniform non-zero field element `j` of the public challenge stream `label` derived from `seed`.
    static func challenge(_ seed: [UInt8], _ label: String, _ j: Int) -> UInt64 {
        var ctr = 0
        while true {
            let h = NetUtil.shaZ([NetUtil.utf8("chal"), seed, NetUtil.utf8("\(label):\(j):\(ctr)")])
            var x: UInt64 = 0
            for i in 0..<8 { x = x << 8 | UInt64(h[i]) }
            x &= MASK61
            if x != 0 && x != MASK61 { return x }
            ctr += 1
        }
    }

    public static func runParty(_ cfg: PartyConfig) throws -> PartyResult { try PartyRun(cfg).run() }

    private struct Opened { var val: UInt64; var mac: [PA] }
    private struct Blame { var g: [UInt64]; var gt: [UInt64]; var a: [UInt64]; var at: [UInt64] }

    private final class PartyRun: Exchanger {
        let cfg: PartyConfig
        let id: Int, n: Int, Q: Int, dealerId: Int, C: Int, K: Int, P: Int
        let mesh: Mesh
        let sessionId: String
        let offlineMode: String
        let beh: Behavior?
        let t0 = DispatchTime.now().uptimeNanoseconds
        var rounds: [RoundStat] = []
        var transcript: [UInt8] = []
        var others: [Int] = []
        var opened: [Opened] = []
        var prep: Prep!
        var env: PaEnv!
        var masked: [UInt64] = []
        var gotMasked: [Int: [UInt64]] = [:]

        init(_ cfg: PartyConfig) {
            self.cfg = cfg
            id = cfg.id
            n = cfg.n
            mesh = cfg.mesh
            sessionId = cfg.sessionId
            Q = cfg.Q ?? NetProtocol.DEFAULT_Q
            dealerId = cfg.dealerId ?? cfg.n
            offlineMode = cfg.offline
            C = NetProtocol.chainCount(cfg.Q ?? NetProtocol.DEFAULT_Q)
            K = Spdz.MAC_KEYS
            P = Spdz.SACRIFICE_PARTNERS
            beh = cfg.behavior
            for i in 0..<cfg.n where i != cfg.id { others.append(i) }
        }

        func ms(_ since: UInt64) -> Double { Double(DispatchTime.now().uptimeNanoseconds - since) / 1e6 }

        func totals() -> (out: Int64, in: Int64) {
            var o: Int64 = 0, i: Int64 = 0
            for s in mesh.stats() { o += s.appBytesOut; i += s.appBytesIn }
            return (o, i)
        }

        func crashIf(_ rd: String) throws {
            if let b = beh, b.round == rd {
                if b.kind == "crash" { throw CrashParty() }
                if b.kind == "silent" { throw SilentParty() }
            }
        }

        func at(_ kind: String, _ rd: String) -> Bool { beh != nil && beh!.kind == kind && beh!.round == rd }

        func bad(_ p: Int, _ what: String) -> NetAbort { NetAbort(kind: "malformed", blamed: p, reporter: id, detail: what) }

        func abort(_ e: NetAbort) -> NetAbort { mesh.fail(e, nil); return e }

        func arr(_ p: Int, _ raw: JSONValue?, _ len: Int) throws -> [UInt64] {
            guard let r = PCAMpc.NetWire.unhxArray(raw, len) else { throw bad(p, "expected \(len) canonical field elements") }
            return r
        }

        func exchange<T>(_ rd: String, _ mine: (Int) -> JSONValue, _ parse: (Int, JSONValue) throws -> T, timeoutMs: Int64?) throws -> [Int: T] {
            try exchange(rd, mine, parse, common: nil, hashed: false, timeoutMs: timeoutMs)
        }

        /// One all-to-all round; `hashed = false` keeps a round (peer-specific tags, forensics) out of the echoed transcript.
        func exchange<T>(_ rd: String, _ mine: (Int) -> JSONValue, _ parse: (Int, JSONValue) throws -> T, common: JSONValue?, hashed: Bool, timeoutMs: Int64?) throws -> [Int: T] {
            try crashIf(rd)
            let a = totals()
            let s = DispatchTime.now().uptimeNanoseconds
            for p in others { try mesh.send(p, rd, mine(p)) }
            let raw = try mesh.collect(rd, from: others, timeoutMs: timeoutMs)
            var parsed: [Int: T] = [:]
            for p in others {
                do {
                    parsed[p] = try parse(p, raw[p]!)
                } catch let e as NetAbort {
                    mesh.fail(e, nil)
                    throw e
                } catch {
                    let ne = NetAbort(kind: "malformed", blamed: p, reporter: id, detail: "round '\(rd)': \(error)")
                    mesh.fail(ne, nil)
                    throw ne
                }
            }
            if hashed {
                // transcript: party order, canonical JSON of what each party broadcast in this round
                transcript += NetUtil.utf8(rd)
                for p in 0..<n { transcript += NetUtil.utf8("|\(p):" + PCAMpc.NetWire.stringify(p == id ? (common ?? .null) : raw[p]!)) }
            }
            let b = totals()
            rounds.append(RoundStat(rd: rd, ms: ms(s), bytesOut: b.out - a.out, bytesIn: b.in - a.in))
            return parsed
        }

        // ---- trusted-dealer prep ----
        func take(_ raw: JSONValue?, _ len: Int) throws -> [UInt64] {
            guard let r = PCAMpc.NetWire.unhxArray(raw, len) else { throw bad(dealerId, "bad prep numbers") }
            return r
        }

        func receiveDealerPrep() throws -> Prep {
            let lay = NetProtocol.prepLayout(n, C, K, P, true)
            var nums: [UInt64] = []
            do {
                let firstRaw = try mesh.recv(dealerId, "prep")
                guard NetUtil.int(firstRaw.jGet("total")) == lay.nums else { throw bad(dealerId, "bad prep size") }
                let chunks = NetUtil.int(firstRaw.jGet("chunks"))
                guard chunks == max(1, (lay.nums + NetProtocol.PREP_CHUNK - 1) / NetProtocol.PREP_CHUNK) else { throw bad(dealerId, "bad prep chunk count") }
                nums += try take(firstRaw.jGet("nums"), min(NetProtocol.PREP_CHUNK, lay.nums))
                for c in stride(from: 1, to: chunks!, by: 1) {
                    let part = try mesh.recv(dealerId, "prep.\(c)")
                    nums += try take(part, min(NetProtocol.PREP_CHUNK, lay.nums - c * NetProtocol.PREP_CHUNK))
                }
            } catch let e as NetAbort {
                throw abort(e)
            } catch {
                throw abort(NetAbort(kind: "malformed", blamed: dealerId, reporter: id, detail: "\(error)"))
            }
            var o = 0
            let delta = nums[o]
            o += 1
            if delta == 0 { throw abort(NetAbort(kind: "dealer", blamed: dealerId, reporter: id, detail: "the dealer gave me a zero verification key")) }
            let w = NetPa.paWidth(n, true)
            var alpha: [PA] = []
            for _ in 0..<K { alpha.append(try NetPa.paParse(nums, o, id, n, true)); o += w }
            let aw = NetPa.awWidth(n, K, true)
            let spt = PCAMpc.NetCodec.sharingsPerTriple(P)
            var triples: [[AW]] = []
            for _ in 0..<lay.triples {
                var sh: [AW] = []
                for _ in 0..<spt { sh.append(try NetPa.awParse(nums, o, id, n, K, true)); o += aw }
                triples.append(sh)
            }
            var inputs: [AW] = []
            for _ in 0..<lay.inputs { inputs.append(try NetPa.awParse(nums, o, id, n, K, true)); o += aw }
            let myPlain = Array(nums[o..<(o + C)])
            return Prep(mode: "trusted-dealer", tagged: true, delta: delta, alpha: alpha, triples: triples, inputs: inputs, myPlain: myPlain, checkMask: nil, forensics: nil)
        }

        func addPub(_ x: AW, _ c: UInt64) throws -> AW { try NetPa.wAddPublic(env, x, c, prep.alpha) }
        func not(_ x: AW) throws -> AW { try addPub(NetPa.wNeg(x), 1) }

        /// Open authenticated values: broadcast value shares, verify pairwise tags (dealer mode), record for the MAC-check.
        func openMany(_ rd: String, _ ws: [AW]) throws -> [UInt64] {
            var sendVals = ws.map { $0.v.x }
            var macs = ws.map { $0.m }
            if let b = beh, rd == b.round {
                if b.kind == "open-lie" { sendVals[0] = Field.add(sendVals[0], 1) }
                if b.kind == "mac-lie" {
                    var m0 = macs[0]
                    m0[0] = PA(x: Field.add(m0[0].x, 1), tag: m0[0].tag, key: m0[0].key)
                    macs[0] = m0
                }
            }
            let common: [JSONValue] = sendVals.map { .string(NetUtil.hx($0)) }
            let sv = sendVals
            let mineFn: (Int) -> JSONValue = { peer in
                if self.at("equivocate", rd) && peer == self.others[0] {
                    var c = common
                    c[0] = .string(NetUtil.hx(Field.add(sv[0], 1)))
                    return .array(c)
                }
                if self.at("short-array", rd) { return .array(Array(common.dropFirst())) }
                if self.at("noncanonical", rd) {
                    var c = common
                    c[0] = .string(NetUtil.hx(Field.prime))
                    return .array(c)
                }
                return .array(common)
            }
            let count = ws.count
            let got = try exchange(rd, mineFn, { p, raw in try self.arr(p, raw, count) }, common: .array(common), hashed: true, timeoutMs: nil)
            if prep.tagged {
                // pairwise tags: peer-specific, so a separate un-echoed round; each receiver verifies at once
                let tagMsg: (Int) -> JSONValue = { peer in
                    .array((0..<count).map { i in
                        let tag = ws[i].v.tag[peer]
                        return .string(NetUtil.hx(self.at("bad-tag", rd) && i == 0 ? Field.add(tag, 1) : tag))
                    })
                }
                let tags = try exchange(rd + ".t", tagMsg, { p, raw in try self.arr(p, raw, count) }, common: nil, hashed: false, timeoutMs: nil)
                for p in others {
                    for i in 0..<count {
                        if !(try NetPa.paVerify(env, ws[i].v, p, got[p]![i], tags[p]![i])) {
                            throw abort(NetAbort(kind: "mac-check", blamed: p, reporter: id,
                                                 detail: "pairwise MAC on party \(p)'s opened share failed in round '\(rd)' (index \(i)): the share or its tag is not what the dealer issued"))
                        }
                    }
                }
            }
            var out: [UInt64] = []
            for i in 0..<count {
                var sum = sendVals[i]
                for p in others { sum = Field.add(sum, got[p]![i]) }
                out.append(sum)
                opened.append(Opened(val: sum, mac: macs[i]))
            }
            return out
        }

        /// Commit / open of a random seed, giving a joint public seed.
        func coin(_ label: String, _ tamperOpen: Bool) throws -> [UInt8] {
            let mySeed = NetUtil.random(32)
            let seedCommit = NetUtil.hex(NetUtil.shaZ([NetUtil.utf8("seed"), NetUtil.utf8(sessionId), NetUtil.utf8(label), NetUtil.utf8(String(id)), mySeed]))
            let seedCommits = try exchange(label + "-c", { _ in .string(seedCommit) }, { p, raw in
                guard NetUtil.isHex(raw.jStr, 64) else { throw self.bad(p, "bad commitment") }
                return raw.jStr!
            }, common: .string(seedCommit), hashed: true, timeoutMs: nil)
            let openMsg: (Int) -> JSONValue = { _ in
                if tamperOpen, let b = self.beh, b.kind == "bad-coin-open" { return .string(NetUtil.hex(NetUtil.random(32))) }
                return .string(NetUtil.hex(mySeed))
            }
            let seeds = try exchange(label + "-o", openMsg, { p, raw in
                guard NetUtil.isHex(raw.jStr, 64), let sd = NetUtil.unhex(raw.jStr!) else { throw self.bad(p, "bad seed") }
                let c = NetUtil.hex(NetUtil.shaZ([NetUtil.utf8("seed"), NetUtil.utf8(self.sessionId), NetUtil.utf8(label), NetUtil.utf8(String(p)), sd]))
                if c != seedCommits[p]! { throw NetAbort(kind: "commitment", blamed: p, reporter: self.id, detail: "party \(p) opened a coin seed that does not match its commitment") }
                return sd
            }, common: .string(NetUtil.hex(mySeed)), hashed: true, timeoutMs: nil)
            var parts: [[UInt8]] = [NetUtil.utf8("joint"), NetUtil.utf8(sessionId), NetUtil.utf8(label)]
            for p in 0..<n { parts.append(p == id ? mySeed : seeds[p]!) }
            return NetUtil.shaZ(parts)
        }

        func sigCommit(_ p: Int, _ s: [UInt64], _ nonce: [UInt8]) -> String {
            NetUtil.hex(NetUtil.shaZ([NetUtil.utf8("sigma"), NetUtil.utf8(sessionId), NetUtil.utf8(String(p)), NetUtil.utf8(s.map { NetUtil.hx($0) }.joined(separator: ",")), nonce]))
        }

        func bitOf(_ x: UInt64) -> Int { x == 1 ? 1 : 0 }

        func bitShare(_ owner: Int, _ k: Int) throws -> AW {
            if prep.mode == "trusted-dealer" {
                let pub = owner == id ? masked[k] : gotMasked[owner]![k]
                return try addPub(prep.inputs[owner * C + k], pub)
            }
            return prep.inputs[owner * C + k]
        }

        func run() throws -> PartyResult {
            if offlineMode == "trusted-dealer" && !cfg.insecureTrustedDealer {
                throw NetAbort(kind: "local", blamed: nil, reporter: id, detail: "offline 'trusted-dealer' requires insecureTrustedDealer (the dealer sees every share and key); the default is 'no-dealer'")
            }
            if beh != nil && !cfg.unsafeTestHooks { throw NetAbort(kind: "local", blamed: nil, reporter: id, detail: "the behavior test hook requires unsafeTestHooks (test-only)") }
            if n < 1 { throw NetAbort(kind: "local", blamed: nil, reporter: id, detail: "n must be >= 1") }
            let v = cfg.input
            if (v.allow != 0 && v.allow != 1) || v.t < 1 || v.t > 3 || v.rQuant < 0 || v.rQuant > Q {
                throw NetAbort(kind: "local", blamed: nil, reporter: id, detail: "invalid decision vector")
            }

            // ---- offline phase ----
            try crashIf("prep")
            let prepStart = DispatchTime.now().uptimeNanoseconds
            let before = totals()
            if offlineMode == "trusted-dealer" {
                prep = try receiveDealerPrep()
            } else {
                let runner: OfflineRunner = cfg.offlineRunner ?? { try NetOffline.run($0) }
                prep = try runner(OfflineCtx(mesh: mesh, id: id, n: n, C: C, keys: K, partners: P, sessionId: sessionId, input: v, Q: Q, behavior: beh, io: self,
                                             crashIf: { try self.crashIf($0) }))
            }
            let afterPrep = totals()
            rounds.append(RoundStat(rd: "prep", ms: ms(prepStart), bytesOut: afterPrep.out - before.out, bytesIn: afterPrep.in - before.in))
            env = PaEnv(id: id, n: n, delta: prep.delta, tagged: prep.tagged)

            // ---- sacrifice: certify every triple against its partners before it is used ----
            let nT = prep.triples.count
            if nT > 0 { try sacrifice(nT) }

            // ---- inputs ----
            let therm = try PCAMpc.Thermometer.encode(Double(v.t), NetProtocol.T_M)
            let rtherm = try PCAMpc.Thermometer.encode(Double(v.rQuant), Q)
            var myBits = [UInt64](repeating: 0, count: C)
            myBits[0] = UInt64(v.allow)
            for i in 0..<NetProtocol.T_M { myBits[1 + i] = UInt64(therm[i]) }
            for i in 0..<Q { myBits[1 + NetProtocol.T_M + i] = UInt64(rtherm[i]) }
            if prep.mode == "trusted-dealer" {
                masked = (0..<C).map { Field.sub(myBits[$0], prep.myPlain[$0]) }
                let maskedMsg: JSONValue = .array(masked.map { .string(NetUtil.hx($0)) })
                gotMasked = try exchange("inputs", { _ in maskedMsg }, { p, raw in try self.arr(p, raw, self.C) }, common: maskedMsg, hashed: true, timeoutMs: nil)
            } else {
                // No-dealer: inputs are already authenticated sharings; MASCOT input-consistency check (joins the batched MAC-check).
                let jointIn = try coin("coin-in", false)
                guard var w = prep.checkMask else { throw NetAbort(kind: "local", blamed: nil, reporter: id, detail: "no-dealer prep carries no check mask") }
                for q in 0..<(n * C) { w = try NetPa.wAdd(w, NetPa.wScale(prep.inputs[q], NetProtocol.challenge(jointIn, "in", q))) }
                _ = try openMany("in-check", [w])
            }

            // ---- chains: acc_c over owners; allow uses AND, the others OR (= NOT AND NOT) ----
            var acc: [AW] = []
            for c in 0..<C {
                let b0 = try bitShare(0, c)
                acc.append(c != 0 ? try not(b0) : b0)
            }
            var mults = 0
            for s in 1..<max(n, 1) where n > 1 {
                var trs: [[AW]] = []
                for c in 0..<C { trs.append(prep.triples[(s - 1) * C + c]) }
                var ds: [AW] = [], es: [AW] = []
                for c in 0..<C {
                    let b = try bitShare(s, c)
                    let y = c != 0 ? try not(b) : b
                    ds.append(try NetPa.wSub(acc[c], trs[c][0]))
                    es.append(try NetPa.wSub(y, trs[c][1]))
                }
                let pub = try openMany("mul\(s - 1)", ds + es)
                var next: [AW] = []
                for c in 0..<C {
                    let d = pub[c], e = pub[C + c]
                    let z = try NetPa.wAdd(trs[c][2], NetPa.wAdd(NetPa.wScale(trs[c][1], d), NetPa.wScale(trs[c][0], e)))
                    next.append(try addPub(z, Field.mul(d, e)))
                }
                acc = next
                mults += C
            }

            // ---- outputs: allow as-is; or-chains are NOT of the product ----
            var outShares: [AW] = []
            for c in 0..<C { outShares.append(c != 0 ? try not(acc[c]) : acc[c]) }
            let outVals = try openMany("out", outShares)

            // ---- MAC-check ----
            let joint = try coin("coin", true)
            var aPub = [UInt64](repeating: 0, count: K), Gamma = [UInt64](repeating: 0, count: K), sigma = [UInt64](repeating: 0, count: K)
            for l in 0..<K {
                var a: UInt64 = 0, g: UInt64 = 0
                for j in 0..<opened.count {
                    let ch = NetProtocol.challenge(joint, "mac\(l)", j)
                    a = Field.add(a, Field.mul(ch, opened[j].val))
                    g = Field.add(g, Field.mul(ch, opened[j].mac[l].x))
                }
                aPub[l] = a
                Gamma[l] = g
                sigma[l] = Field.sub(g, Field.mul(prep.alpha[l].x, a))
            }
            let sigNonce = NetUtil.random(32)
            var sigmaSent = sigma
            if let b = beh, b.kind == "sigma-lie" { sigmaSent[0] = Field.add(sigmaSent[0], 1) }
            let mySigCommit = sigCommit(id, sigmaSent, sigNonce)
            let sigCommits = try exchange("sig-c", { _ in .string(mySigCommit) }, { p, raw in
                guard NetUtil.isHex(raw.jStr, 64) else { throw self.bad(p, "bad commitment") }
                return raw.jStr!
            }, common: .string(mySigCommit), hashed: true, timeoutMs: nil)
            func sigOpen(_ s: [UInt64]) -> JSONValue { .object(["s": NetUtil.hxList(s), "nonce": .string(NetUtil.hex(sigNonce))]) }
            let mySigOpen = sigOpen(sigmaSent)
            let kk = K
            let sigOpens = try exchange("sig-o", { _ in
                if let b = self.beh, b.kind == "bad-sigma-open" {
                    var s2 = sigmaSent
                    s2[0] = Field.add(s2[0], 1)
                    return sigOpen(s2)
                }
                return mySigOpen
            }, { p, raw in
                guard let sv = PCAMpc.NetWire.unhxArray(raw.jGet("s"), kk), NetUtil.isHex(raw.jGet("nonce")?.jStr, 64), let nonce = NetUtil.unhex(raw.jGet("nonce")!.jStr!) else {
                    throw self.bad(p, "bad sigma opening")
                }
                if self.sigCommit(p, sv, nonce) != sigCommits[p]! {
                    throw NetAbort(kind: "commitment", blamed: p, reporter: self.id, detail: "party \(p) opened a MAC residual that does not match its commitment")
                }
                return sv
            }, common: mySigOpen, hashed: true, timeoutMs: nil)
            var macFailed = false
            for l in 0..<K {
                var r = sigmaSent[l]
                for p in others { r = Field.add(r, sigOpens[p]![l]) }
                if r != 0 { macFailed = true }
            }

            // ---- transcript echo: everyone must have seen the same broadcasts ----
            let digest = NetUtil.hex(NetUtil.sha256([transcript]))
            let digests = try exchange("digest", { _ in .string(digest) }, { p, raw in
                guard NetUtil.isHex(raw.jStr, 64) else { throw self.bad(p, "bad digest") }
                return raw.jStr!
            }, common: .string(digest), hashed: true, timeoutMs: nil)
            for p in others where digest != digests[p]! {
                throw abort(NetAbort(kind: "equivocation", blamed: p, reporter: id, detail: "transcript digest of party \(p) differs from mine (a broadcast was inconsistent)"))
            }

            if macFailed { try blame(aPub, Gamma, sigOpens, joint) }

            // ---- only now decode ----
            var tBits: [Int] = [], rBits: [Int] = []
            for i in 0..<NetProtocol.T_M { tBits.append(bitOf(outVals[1 + i])) }
            for i in 0..<Q { rBits.append(bitOf(outVals[1 + NetProtocol.T_M + i])) }
            let composed = DecisionVector(allow: bitOf(outVals[0]), t: min(3, max(1, PCAMpc.Thermometer.decode(tBits))), rQuant: PCAMpc.Thermometer.decode(rBits))
            mesh.finish()
            return PartyResult(id: id, n: n, Q: Q, composed: composed, rounds: rounds, transcriptDigest: digest, wallMs: ms(t0), multiplications: mults, opens: opened.count,
                               offlineMode: prep.mode, macKeys: K, sacrificedTriples: nT, sacrificePartners: P, identifiableAbort: prep.tagged)
        }

        func sacrifice(_ nT: Int) throws {
            let joint1 = try coin("coin1", false)
            // a peer that detects the failed sacrifice sends its tau share and disclosures and then its abort claim back to back; the claim is read in link order, after every frame that peer sent before it, so this party finishes its OWN verified detection instead of reporting the peer's unverified accusation
            mesh.setDeferAborts(true)
            var rhoW: [AW] = []
            for t in 0..<nT {
                let tr = prep.triples[t]
                for r in 0..<P {
                    let e = NetProtocol.challenge(joint1, "sac", t * P + r)
                    rhoW.append(try NetPa.wSub(NetPa.wScale(tr[0], e), tr[3 + 2 * r]))
                }
            }
            let rho = try openMany("sac-rho", rhoW)
            var tauW: [AW] = []
            for t in 0..<nT {
                let tr = prep.triples[t]
                for r in 0..<P {
                    let e = NetProtocol.challenge(joint1, "sac", t * P + r)
                    tauW.append(try NetPa.wSub(NetPa.wSub(NetPa.wScale(tr[2], e), tr[3 + 2 * r + 1]), NetPa.wScale(tr[1], rho[t * P + r])))
                }
            }
            let tau = try openMany("sac-tau", tauW)
            guard let badAt = tau.firstIndex(where: { $0 != 0 }) else { mesh.setDeferAborts(false); return }
            // Dealer-free mode: the triple is discarded, so its OT transcript can be disclosed and audited to name a party that fed a wrong operand.
            var attributed: Int? = nil
            var note = ""
            if prep.mode == "no-dealer", let fx = prep.forensics {
                let bt = badAt / P
                let mine = fx.disclose(bt)
                // commit first, open only once every commitment is in hand; a late or absent party times out at the shared deadline
                let deadline = cfg.forensicDeadlineMs ?? PCAMpc.NetForensics.DEFAULT_FORENSIC_DEADLINE_MS
                var all = try NetForensic.exchangeDisclosures(sessionId, id, n, bt, mine, fx.slots, fx.rows, Int64(deadline), self)
                all[id] = mine
                let res = try PCAMpc.NetForensics.auditDisclosures(all, fx.gadget)
                attributed = PCAMpc.NetForensics.blameFrom(id, res)
                note = attributed == nil
                    ? " (OT transcript audit: \(res.pairBad.count) inconsistent pair(s), no party can be named from this view: a pair failure between two other parties is not evidence against either of them to me)"
                    : " (OT transcript audit names party \(attributed!))"
            }
            let dealer = prep.mode == "trusted-dealer"
            let blamed: Int? = dealer ? dealerId : (attributed ?? (n == 2 ? 1 - id : nil))
            throw abort(NetAbort(kind: dealer ? "dealer" : "mac-check", blamed: blamed, reporter: id,
                                 detail: "triple sacrifice FAILED at triple \(badAt / P) (partner \(badAt % P)): c != a*b in the offline material; aborting with no output" + note,
                                 reason: "the triple sacrifice failed in dealer-free mode and the OT transcript audit of this party's own view names no one (a failing pair that does not involve me is not evidence I can use, and an accusation is never accepted as evidence)"))
        }

        func blame(_ aPub: [UInt64], _ Gamma: [UInt64], _ sigOpens: [Int: [UInt64]], _ joint: [UInt8]) throws {
            let msg = "MAC-check FAILED: an opened value or MAC share was inconsistent; aborting with no output"
            if !prep.tagged {
                throw abort(NetAbort(kind: "mac-check", blamed: n == 2 ? 1 - id : nil, reporter: id, detail: msg,
                                     reason: "this mode carries no pairwise tags, so a MAC-check failure cannot name a party (only possible with two parties)"))
            }
            // every party opens its combined MAC shares with their pairwise tags; each verifier checks them
            let kk = K
            let blameMsg: (Int) -> JSONValue = { peer in
                var gt: [UInt64] = [], a: [UInt64] = [], at: [UInt64] = []
                for l in 0..<kk {
                    var g: UInt64 = 0
                    for j in 0..<self.opened.count { g = Field.add(g, Field.mul(NetProtocol.challenge(joint, "mac\(l)", j), self.opened[j].mac[l].tag[peer])) }
                    gt.append(g)
                    a.append(self.prep.alpha[l].x)
                    at.append(self.prep.alpha[l].tag[peer])
                }
                return .object(["g": NetUtil.hxList(Gamma), "gt": NetUtil.hxList(gt), "a": NetUtil.hxList(a), "at": NetUtil.hxList(at)])
            }
            // Abort claims arriving during this round are read in link order (see Mesh.setDeferAborts).
            mesh.setDeferAborts(true)
            let blames: [Int: Blame]
            do {
                blames = try exchange("blame", blameMsg, { p, raw in
                    Blame(g: try self.arr(p, raw.jGet("g"), kk), gt: try self.arr(p, raw.jGet("gt"), kk), a: try self.arr(p, raw.jGet("a"), kk), at: try self.arr(p, raw.jGet("at"), kk))
                }, common: nil, hashed: false, timeoutMs: nil)
            } catch {
                mesh.setDeferAborts(false)
                throw error
            }
            mesh.setDeferAborts(false)
            for p in others {
                let b = blames[p]!
                for l in 0..<K {
                    var keyCombo: UInt64 = 0
                    for j in 0..<opened.count { keyCombo = Field.add(keyCombo, Field.mul(NetProtocol.challenge(joint, "mac\(l)", j), opened[j].mac[l].key[p])) }
                    if Field.add(keyCombo, Field.mul(env.delta, b.g[l])) != b.gt[l] {
                        throw abort(NetAbort(kind: "mac-check", blamed: p, reporter: id, detail: msg + " - party \(p)'s MAC share (key \(l)) does not match its pairwise tag"))
                    }
                    if Field.add(prep.alpha[l].key[p], Field.mul(env.delta, b.a[l])) != b.at[l] {
                        throw abort(NetAbort(kind: "mac-check", blamed: p, reporter: id, detail: msg + " - party \(p)'s key share (key \(l)) does not match its pairwise tag"))
                    }
                    if Field.sub(b.g[l], Field.mul(b.a[l], aPub[l])) != sigOpens[p]![l] {
                        throw abort(NetAbort(kind: "mac-check", blamed: p, reporter: id, detail: msg + " - party \(p)'s opened MAC residual (key \(l)) is not what its authenticated shares give"))
                    }
                }
            }
            // Every other party's data is consistent with its pairwise tags; so is mine: the offline material disagrees.
            if prep.mode == "trusted-dealer" {
                throw abort(NetAbort(kind: "dealer", blamed: dealerId, reporter: id, detail: msg + " - every party's shares verify, so the trusted dealer's MACs are inconsistent with its values"))
            }
            throw abort(NetAbort(kind: "mac-check", blamed: n == 2 ? 1 - id : nil, reporter: id,
                                 detail: msg + " - every party's shares verify under its pairwise tags, so the offline material is inconsistent (a wrong OT operand): not attributable",
                                 reason: "every party's shares verify under its pairwise tags, so the fault lies in the offline material, which names no party"))
        }
    }
