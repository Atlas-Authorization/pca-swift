/// The offline material one party holds when the online phase starts, dealt by a trusted dealer or generated by the parties from OT.
public struct Prep {
    /// "trusted-dealer" or "no-dealer". A trusted dealer knows every share and key.
    public var mode: String
    /// Whether the shares carry pairwise tags (identifiable abort).
    public var tagged: Bool
    public var delta: UInt64
    public var alpha: [PA]
    /// triples[t] = a, b, c, then (a-hat, c-hat) per sacrifice partner.
    public var triples: [[AW]]
    /// Authenticated masks (dealer) or input bits (no-dealer), indexed owner * C + chain.
    public var inputs: [AW]
    public var myPlain: [UInt64]
    public var checkMask: AW?
    public var forensics: PrepForensics?
}

