/// One un-echoed all-to-all round among the parties; a throw inside `parse` aborts the run naming that peer.
public protocol Exchanger: AnyObject {
    /// Send `mine(peer)` to every peer, collect theirs and validate each with `parse`; `timeoutMs` nil means the mesh default.
    func exchange<T>(_ rd: String, _ mine: (Int) -> JSONValue, _ parse: (Int, JSONValue) throws -> T, timeoutMs: Int64?) throws -> [Int: T]
    /// A malformed-data abort naming peer `p`; callers `throw` the result.
    func bad(_ p: Int, _ what: String) -> NetAbort
}

extension Exchanger {
    public func exchange<T>(_ rd: String, _ mine: (Int) -> JSONValue, _ parse: (Int, JSONValue) throws -> T) throws -> [Int: T] {
        try exchange(rd, mine, parse, timeoutMs: nil)
    }
}

