import XCTest
import Foundation
@testable import AtlasPCAVerify

/// Differential replay of PCADpop against the reference (@atlasauth/pca-dpop): thumbprints, alg mapping, htu normalization,
/// server nonces, replay stores, proof creation (Ed25519 byte-exact) and verification, mTLS confirmation and the PCActn binding.
/// Ed448 and RSA signing (and Ed448 verification) come from the opt-in AtlasPCAOpenSSL product; without it those cases are refused natively (skipped).
final class RefDpopTests: XCTestCase {
    static let file = "ref-dpop.json.gz"
    static let T0: Double = 1_800_000_000

    struct FixedStore: DpopReplayStore {
        let answer: Bool?
        func addIfAbsent(_ key: String, expiresAtSec: Double, nowSec: Double) throws -> Bool {
            guard let a = answer else { throw JSError("boom") }
            return a
        }
    }

    final class NoExpiryStore: DpopReplayStore {
        var seen: Set<String> = []
        let lock = NSLock()
        func addIfAbsent(_ key: String, expiresAtSec: Double, nowSec: Double) throws -> Bool {
            lock.lock(); defer { lock.unlock() }
            return seen.insert(key).inserted
        }
    }

    static func num(_ v: JSONValue?) -> Double? { v.flatMap { IV.num($0) } }

    static func store(_ s: JSONValue) throws -> DpopReplayStore {
        switch s.get("kind") {
        case .string("memory")?:
            let st = try InMemoryDpopReplayStore(maxEntries: s.get("maxEntries"))
            for p in s.get("preload")?.asArray ?? [] {
                guard let a = p.asArray, a.count == 3, let k = a[0].asString, let e = num(a[1]), let n = num(a[2]) else { continue }
                _ = try? st.addIfAbsent(k, expiresAtSec: e, nowSec: n)
            }
            return st
        case .string("true")?: return FixedStore(answer: true)
        case .string("false")?: return FixedStore(answer: false)
        default: return FixedStore(answer: nil)
        }
    }

    /// The generator's option adapter; nil when the options are outside the typed surface.
    static func opts(_ v: JSONValue?) throws -> (PCADpop.VerifyOptions, DpopJtiSet?)? {
        let o = Ref.obj(v)
        guard let m = o["method"]?.asString, let u = o["url"]?.asString else { return nil }
        var r = PCADpop.VerifyOptions(method: m, url: u)
        r.maxAgeSec = num(o["maxAgeSec"])
        r.expectedJkt = o["expectedJkt"]?.asString
        r.expectedNonce = o["expectedNonce"]?.asString
        r.accessToken = o["accessToken"]?.asString
        r.nowSec = num(o["nowSec"])
        if case let .bool(b)? = o["requireReplayStore"] { r.requireReplayStore = b }
        var seen: DpopJtiSet? = nil
        if let s = o["seenJti"] {
            guard let list = Ref.strings(s) else { return nil }
            seen = DpopJtiSet(list)
            r.seenJti = seen
        }
        if let s = o["replayStore"] { r.replayStore = try store(s) }
        if let n = o["nonceIssuer"] {
            r.nonceIssuer = try DpopNonceIssuer(secret: n.get("secret")?.asString.flatMap { Base64URLStrict.decode($0) }, ttlSec: n.get("ttl"))
        }
        return (r, seen)
    }

    static func withSeen(_ r: JSONValue, _ seen: DpopJtiSet?) -> JSONValue {
        guard var o = r.asObject else { return r }
        if let s = seen { o["seen"] = .array(s.items.map { .string($0) }) }
        return .object(o)
    }

    static func cert(_ v: JSONValue?) -> PCADpop.CertInput? {
        if let b = Base.bytes(v) { return .der(b) }
        return v?.asString.map { .pem($0) }
    }

    /// The embedded key's curve of a proof (to recognise the Ed448 cases).
    static func headerCrv(_ v: JSONValue?) -> JSONValue? {
        guard let s = v?.asString, let h = s.split(separator: ".", omittingEmptySubsequences: false).first,
              let b = Base64URLStrict.decode(String(h)), let t = String(bytes: b, encoding: .utf8), let j = try? StrictJSON.parse(t) else { return nil }
        return j.get("jwk")?.get("crv")
    }

    func testDpop() throws { try replay(Self.file, min: 950) }

    /// ref-dpop-rsa.json.gz is generated by CI (never committed): a missing file fails under CI, else skips.
    func testDpopRSA() throws {
        let env = ProcessInfo.processInfo.environment
        let path = env["PCA_DPOP_RSA_CORPUS"] ?? K042.dataURL("ref-dpop-rsa.json.gz").path
        guard FileManager.default.fileExists(atPath: path) else {
            if env["CI"] == "true" || env["CI"] == "1" { XCTFail("RSA DPoP corpus missing (\(path)): CI must generate it with .github/scripts/dpop-rsa-corpus.sh"); return }
            throw XCTSkip("RSA DPoP corpus missing (\(path)): run .github/scripts/dpop-rsa-corpus.sh")
        }
        try replay(path, min: 0)
    }

    func replay(_ file: String, min: Int) throws {
        OpenSSLOptIn.register()
        try K042.requireCovers(["Dpop", "Jose", "WhatwgURL", "JSInterop"])
        let d = Base.Diffs()
        try Base.each(file, seeds: true) { c in
            let a0 = c.arg(0), a1 = c.arg(1)
            let got: BaseGot
            switch c.fn {
            case "constants":
                got = .value(.object([
                    "allowedAlgs": .array(PCADpop.ALLOWED_ALGS.map { .string($0) }), "typ": .string(PCADpop.JWT_TYP),
                    "defaultMaxAgeSec": .int(Int64(PCADpop.DEFAULT_MAX_AGE_SEC)), "clockSkewSec": .int(Int64(PCADpop.CLOCK_SKEW_SEC)),
                    "maxProofBytes": .int(Int64(PCADpop.MAX_PROOF_BYTES)), "inMemoryMaxEntries": .int(Int64(PCADpop.INMEMORY_MAX_ENTRIES)),
                ]))
            case "jwkThumbprint":
                got = Ref.s { try PCADpop.jwkThumbprint(a0, digest: a1) }
            case "dpopAlgForJwk":
                got = Ref.s { try PCADpop.dpopAlgForJwk(a0) }
            case "dpopAlgMatchesJwk":
                got = Ref.v { .bool(try PCADpop.dpopAlgMatchesJwk(a0, a1)) }
            case "normalizeHtu":
                got = Ref.s { try PCADpop.normalizeHtu(a0) }
            case "athFor":
                guard let t = a0?.asString else { d.skip("athFor: non-string token"); return }
                got = .value(.string(PCADpop.athFor(t)))
            case "nonceIssuer":
                got = Ref.v {
                    let iss = try DpopNonceIssuer(secret: a0?.asString.flatMap { Base64URLStrict.decode($0) }, ttlSec: a1)
                    var issued: [String] = []
                    var out: [JSONValue] = []
                    for op in c.arg(2)?.asArray ?? [] {
                        if op.get("op") == .string("issue") {
                            let n = try iss.issue(nowSec: Self.num(op.get("now")))
                            issued.append(n); out.append(.string(n))
                        } else {
                            var nonce = op.get("nonce")
                            if let i = nonce?.get("$issued")?.safeInt { nonce = Int(i) < issued.count ? .string(issued[Int(i)]) : nil }
                            out.append(.bool(iss.check(nonce, nowSec: Self.num(op.get("now")))))
                        }
                    }
                    return .array(out)
                }
            case "replayStore":
                got = Ref.v {
                    let st = try InMemoryDpopReplayStore(maxEntries: a0)
                    return .array((a1?.asArray ?? []).map { op -> JSONValue in
                        guard let k = op.get("key")?.asString, let e = Self.num(op.get("exp")), let n = Self.num(op.get("now")) else { return .string("throws") }
                        return (try? st.addIfAbsent(k, expiresAtSec: e, nowSec: n)).map { .bool($0) } ?? .string("throws")
                    })
                }
            case "replayConformance":
                let kind = a0?.asString ?? ""
                got = Ref.v {
                    .array(try PCADpop.runReplayStoreConformance { () throws -> DpopReplayStore in
                        switch kind {
                        case "memory": return try InMemoryDpopReplayStore()
                        case "alwaysTrue": return FixedStore(answer: true)
                        case "alwaysFalse": return FixedStore(answer: false)
                        default: return NoExpiryStore()
                        }
                    }.map { .string($0) })
                }
            case "createDpopProof", "createThenVerify":
                let priv = a0?.get("privateKey")
                let unsignable = priv?.get("kty") == .string("RSA") || priv?.get("crv") == .string("Ed448")
                if c.fn == "createDpopProof" {
                    got = Ref.s { try PCADpop.createDpopProof(a0) }
                } else {
                    var vo: JObject = ["method": a0?.get("method") ?? .null, "url": a0?.get("url") ?? .null, "maxAgeSec": .int(300),
                                       "nowSec": .double((Self.num(a0?.get("iat")) ?? Self.T0) + 1), "seenJti": .array([])]
                    for (k, v) in Ref.obj(a1) { vo[k] = v }
                    guard let r = try Self.opts(.object(vo)) else { d.skip("createThenVerify: untyped options"); return }
                    let (o, seen) = r
                    got = Ref.v { Self.withSeen(try PCADpop.verifyDpopProof(.string(try PCADpop.createDpopProof(a0)), o), seen) }
                }
                if unsignable, case let .threw(code) = got, code == "unsupported_key" { XCTAssertFalse(OpenSSLOptIn.linked, "the OpenSSL signers are not registered"); d.skip("Ed448 / RSA signing: no vetted signer (refused)"); return }
            case "verifyDpopProof", "assertPcaDpop":
                let proof = c.fn == "verifyDpopProof" ? a0 : a1
                guard let r = try Self.opts(c.fn == "verifyDpopProof" ? a1 : c.arg(2)) else { d.skip("\(c.fn): untyped options"); return }
                let (o, seen) = r
                got = Ref.v {
                    Self.withSeen(c.fn == "verifyDpopProof" ? try PCADpop.verifyDpopProof(proof, o) : try PCADpop.assertPcaDpop(a0, proof, o), seen)
                }
                if Self.headerCrv(proof) == .string("Ed448"), Base.diff(c, got) != nil, case let .threw(code) = got, code == "signature" {
                    XCTAssertFalse(OpenSSLOptIn.linked, "the Ed448 verifier is not registered"); d.skip("Ed448 verification: no vetted verifier (refused as signature)"); return
                }
            case "mtlsCnf":
                guard let ct = Self.cert(a0) else { d.skip("mtls: untyped cert"); return }
                got = .value(PCADpop.mtlsCnf(ct))
            case "mtlsThumbprint":
                guard let ct = Self.cert(a0) else { d.skip("mtls: untyped cert"); return }
                got = Ref.s { try PCADpop.mtlsThumbprint(ct) }
            case "assertMtlsBound":
                guard let ct = Self.cert(a0) else { d.skip("mtls: untyped cert"); return }
                got = Ref.v { try PCADpop.assertMtlsBound(ct, a1) }
            case "leafHolderJwk":
                got = Ref.v { try PCADpop.leafHolderJwk(a0) }
            case "bindPcaToDpop":
                got = Ref.v { try PCADpop.bindPcaToDpop(a0) }
            default:
                d.skip("\(c.fn): not mapped"); return
            }
            d.add(c, Base.diff(c, got))
        }
        d.finish(min)
    }

    func testDpopFailClosed() throws {
        // a missing replay store is refused unless explicitly waived; a non-finite max age is refused
        let o = PCADpop.VerifyOptions(method: "POST", url: "https://a.example/x")
        XCTAssertThrowsError(try PCADpop.verifyDpopProof(.string("a.b.c"), o)) { XCTAssertEqual(($0 as? JSError)?.code, "replay_store_required") }
        var p = o
        p.seenJti = DpopJtiSet()
        p.maxAgeSec = .infinity
        XCTAssertThrowsError(try PCADpop.verifyDpopProof(.string("a.b.c"), p)) { XCTAssertEqual(($0 as? JSError)?.code, "max_age") }
        p.maxAgeSec = .nan
        XCTAssertThrowsError(try PCADpop.verifyDpopProof(.string("a.b.c"), p)) { XCTAssertEqual(($0 as? JSError)?.code, "max_age") }
        XCTAssertThrowsError(try DpopNonceIssuer(secret: [UInt8](repeating: 1, count: 31)))
        XCTAssertThrowsError(try InMemoryDpopReplayStore(maxEntries: .int(0)))
    }

    func testDpopNonFiniteNowRefused() throws {
        // a non-finite nowSec would void the freshness window: refused
        var input: JSONValue? = nil
        _ = try Base.each(Self.file, seeds: true) { c in
            if input == nil, c.fn == "createThenVerify", c.arg(0)?.get("privateKey")?.get("crv") == .string("Ed25519") { input = c.arg(0) }
        }
        let proof = try PCADpop.createDpopProof(input)
        var q = PCADpop.VerifyOptions(method: input?.get("method")?.asString ?? "", url: input?.get("url")?.asString ?? "")
        q.requireReplayStore = false
        q.nowSec = (Self.num(input?.get("iat")) ?? Self.T0) + 1
        XCTAssertNoThrow(try PCADpop.verifyDpopProof(.string(proof), q))
        for v in [Double.nan, .infinity, -.infinity] {
            q.nowSec = v
            XCTAssertThrowsError(try PCADpop.verifyDpopProof(.string(proof), q)) { XCTAssertEqual(($0 as? JSError)?.code, "now") }
        }
    }
}
