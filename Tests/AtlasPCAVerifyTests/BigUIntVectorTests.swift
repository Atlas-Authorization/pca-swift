    func testArithmeticMatchesBigIntegers() {
        XCTAssertGreaterThan(Self.arith.count, 100)
        for (a, b, sum, diff, prod, lt) in Self.arith {
            let x = make(a), y = make(b)
            XCTAssertEqual(hex(x), a, "ctor \(a)")
            XCTAssertEqual(hex(x + y), sum, "\(a) + \(b)")
            XCTAssertEqual(hex(y + x), sum, "\(b) + \(a)")
            XCTAssertEqual(hex(x * y), prod, "\(a) * \(b)")
            XCTAssertEqual(hex(y * x), prod, "\(b) * \(a)")
            XCTAssertEqual(x < y, lt == 1, "\(a) < \(b)")
            XCTAssertEqual(x == y, a == b)
            if !(x < y) { XCTAssertEqual(hex(x - y), diff, "\(a) - \(b)") }
            if !(y < x) { XCTAssertEqual(hex(y - x), diff, "\(b) - \(a)") }
        }
    }

    func testShiftsMatchBigIntegers() {
        for (a, s, want) in Self.shifts { XCTAssertEqual(hex(make(a) << s), want, "\(a) << \(s)") }
    }

    func testBitsAndBitLength() {
        for (a, i, bit, n) in Self.bits {
            XCTAssertEqual(make(a).bit(i), bit, "bit \(i) of \(a)")
            XCTAssertEqual(make(a).bitLength, n, "bitLength of \(a)")
        }
    }

    func testByteConstructorAtEveryLength() {
        for n in 0...13 {
            let bytes = (0..<n).map { UInt8(truncatingIfNeeded: 0xa1 &+ $0 &* 7) }
            var want = BigUInt()
            for (i, b) in bytes.enumerated() { want = want + (BigUInt(UInt64(b)) << (8 * i)) }
            XCTAssertTrue(BigUInt(bytesLE: bytes) == want, "\(n) bytes")
            let ones = [UInt8](repeating: 0xff, count: n)
            XCTAssertEqual(BigUInt(bytesLE: ones).bitLength, 8 * n, "\(n) 0xff bytes")
            XCTAssertEqual(BigUInt(bytesLE: ones + [0, 0, 0]).bitLength, 8 * n, "\(n) 0xff bytes + zero padding")
        }
    }

    func testDecimalConstructor() {
        XCTAssertTrue(BigUInt(decimal: "") .isZero)
        XCTAssertTrue(BigUInt(decimal: "0").isZero)
        XCTAssertTrue(BigUInt(decimal: "9") == BigUInt(9))
        XCTAssertTrue(BigUInt(decimal: "10") == BigUInt(10))
        XCTAssertTrue(BigUInt(decimal: "0000012") == BigUInt(12))
        XCTAssertTrue(BigUInt(decimal: "1234567890") == BigUInt(1_234_567_890))
        XCTAssertTrue(BigUInt(decimal: "4294967296") == (BigUInt(1) << 32))
        XCTAssertTrue(BigUInt(decimal: "18446744073709551615") == BigUInt(UInt64.max))
        XCTAssertEqual(hex(BigUInt(decimal: "57896044618658097711785492504343953926634992332820282019728792003956564819949")), "7fffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffed")
    }

    func testUInt64Constructor() {
        XCTAssertTrue(BigUInt(0).limbs.isEmpty)
        XCTAssertEqual(BigUInt(1).limbs, [1])
        XCTAssertEqual(BigUInt(0xffff_ffff).limbs, [0xffff_ffff])
        XCTAssertEqual(BigUInt(0x1_0000_0000).limbs, [0, 1])
        XCTAssertEqual(BigUInt(UInt64.max).limbs, [0xffff_ffff, 0xffff_ffff])
        XCTAssertEqual(BigUInt(0xabcd_ef01_2345_6789).limbs, [0x2345_6789, 0xabcd_ef01])
    }
