        // big-endian hex -> little-endian bytes
        var s = hex
        if s.count % 2 == 1 { s = "0" + s }
        var bytes: [UInt8] = []
        var i = s.endIndex
        while i > s.startIndex {
            let j = s.index(i, offsetBy: -2)
            bytes.append(UInt8(s[j..<i], radix: 16)!)
            i = j
        }
        return BigUInt(bytesLE: bytes)
    }
